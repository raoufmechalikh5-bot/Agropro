import com.example.LocaleHelper

@Composable
fun agroText(source: String): String {
    val context = LocalContext.current
    val language = LocaleHelper.getLanguage(context)
    if (language == "ar" || language == "system") return source
    val translated = if (language == "fr") frenchText[source] else englishText[source]
    return translated ?: source
}

